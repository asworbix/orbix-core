//! The ORBIX wordmark shown on first run.

use std::io::Write;

use anstyle::{Ansi256Color, Style};


/// The ORBIX wordmark, pink to orange, top to bottom. The same gradient the
/// platform uses everywhere else. anstream strips it for pipes.
pub fn print_wordmark() {
    let rows: [(u8, &str); 6] = [
        (205, "\u{2588}\u{2588}\u{2588}\u{2588}\u{2588}\u{2588}\u{2557}  \u{2588}\u{2588}\u{2588}\u{2588}\u{2588}\u{2588}\u{2557}  \u{2588}\u{2588}\u{2588}\u{2588}\u{2588}\u{2588}\u{2557}  \u{2588}\u{2588}\u{2557} \u{2588}\u{2588}\u{2557}  \u{2588}\u{2588}\u{2557}"),
        (204, "\u{2588}\u{2588}\u{2554}\u{2550}\u{2550}\u{2588}\u{2588}\u{2557} \u{2588}\u{2588}\u{2554}\u{2550}\u{2550}\u{2588}\u{2588}\u{2557} \u{2588}\u{2588}\u{2554}\u{2550}\u{2550}\u{2588}\u{2588}\u{2557} \u{2588}\u{2588}\u{2551} \u{255a}\u{2588}\u{2588}\u{2557}\u{2588}\u{2588}\u{2554}\u{255d}"),
        (210, "\u{2588}\u{2588}\u{2551}  \u{2588}\u{2588}\u{2551} \u{2588}\u{2588}\u{2588}\u{2588}\u{2588}\u{2588}\u{2554}\u{255d} \u{2588}\u{2588}\u{2588}\u{2588}\u{2588}\u{2588}\u{2566}\u{255d} \u{2588}\u{2588}\u{2551}  \u{255a}\u{2588}\u{2588}\u{2588}\u{2554}\u{255d}"),
        (209, "\u{2588}\u{2588}\u{2551}  \u{2588}\u{2588}\u{2551} \u{2588}\u{2588}\u{2554}\u{2550}\u{2550}\u{2588}\u{2588}\u{2557} \u{2588}\u{2588}\u{2554}\u{2550}\u{2550}\u{2588}\u{2588}\u{2557} \u{2588}\u{2588}\u{2551}  \u{2588}\u{2588}\u{2554}\u{2588}\u{2588}\u{2557}"),
        (208, "\u{255a}\u{2588}\u{2588}\u{2588}\u{2588}\u{2588}\u{2588}\u{2554}\u{255d} \u{2588}\u{2588}\u{2551}  \u{2588}\u{2588}\u{2551} \u{2588}\u{2588}\u{2588}\u{2588}\u{2588}\u{2588}\u{2566}\u{255d} \u{2588}\u{2588}\u{2551} \u{2588}\u{2588}\u{2554}\u{255d} \u{2588}\u{2588}\u{2557}"),
        (202, " \u{255a}\u{2550}\u{2550}\u{2550}\u{2550}\u{2550}\u{255d}  \u{255a}\u{2550}\u{255d}  \u{255a}\u{2550}\u{255d} \u{255a}\u{2550}\u{2550}\u{2550}\u{2550}\u{2550}\u{255d}  \u{255a}\u{2550}\u{255d} \u{255a}\u{2550}\u{255d}  \u{255a}\u{2550}\u{255d}"),
    ];
    let mut out = anstream::stdout().lock();
    let _ = writeln!(out);
    for (c, row) in rows {
        let s = Style::new().fg_color(Some(Ansi256Color(c).into()));
        let _ = writeln!(out, "  {}{}{}", s.render(), row, s.render_reset());
    }
    let dim = Style::new().fg_color(Some(Ansi256Color(209).into())).dimmed();
    let _ = writeln!(out, "  {}              C  O  R  E{}", dim.render(), dim.render_reset());
}
